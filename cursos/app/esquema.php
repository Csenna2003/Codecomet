            token_hash CHAR(64) NULL,
            resposta_nome VARCHAR(150) NULL,
            resposta_comentario TEXT NULL,
            resposta_em DATETIME NULL,
            resposta_ip VARCHAR(45) NULL,
            criado_em DATETIME NOT NULL,
            KEY (aluno_id, chegada),
            KEY (professor_id, chegada),
            UNIQUE KEY (token_hash),
            FOREIGN KEY (particular_id) REFERENCES particulares(id) ON DELETE CASCADE,
            FOREIGN KEY (aluno_id) REFERENCES usuarios(id) ON DELETE CASCADE,
            FOREIGN KEY (professor_id) REFERENCES usuarios(id) ON DELETE CASCADE
        ) $t",
        "CREATE TABLE IF NOT EXISTS emails_log (
            id BIGINT AUTO_INCREMENT PRIMARY KEY,
            para VARCHAR(190) NOT NULL,
            assunto VARCHAR(200) NOT NULL,
            enviado TINYINT(1) NOT NULL,

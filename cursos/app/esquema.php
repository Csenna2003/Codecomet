            FOREIGN KEY (professor_id) REFERENCES usuarios(id) ON DELETE CASCADE
        ) $t",
        "CREATE TABLE IF NOT EXISTS aulas_particulares (
            id CHAR(20) PRIMARY KEY,
            particular_id CHAR(20) NOT NULL,

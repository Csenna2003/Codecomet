        ) $t",
        "CREATE TABLE IF NOT EXISTS redefinicoes (
            token_hash CHAR(64) PRIMARY KEY,
            usuario_id CHAR(20) NOT NULL,
            criado_por CHAR(20) NOT NULL,
            expira_em DATETIME NOT NULL,
            usado_em DATETIME NULL,
